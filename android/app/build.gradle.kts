import java.util.Properties
import java.io.FileInputStream

// Release signing config — loaded from android/key.properties, which
// is never committed to git (see .gitignore). Locally this file won't
// exist, so release signing falls back to the debug key (matches
// Flutter's own default) — `flutter run --release` still works
// without needing the real Play Store key on every machine. In CI,
// the release workflow writes this file (and the keystore it points
// to) from GitHub Secrets right before building, then both are
// discarded when the runner is torn down.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
val hasReleaseSigning = keystorePropertiesFile.exists()
if (hasReleaseSigning) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
}

